def language() -> str:
    return _language


def set_language(value: str) -> None:
    global _language
    _language = "ru" if value.lower().startswith("ru") else "en"


def tr(text: str) -> str:
    """Translate exact UI strings and composed diagnostic text."""
    if _language == "ru" or not isinstance(text, str):
        return text
    exact = RU_TO_EN.get(text)
    if exact is not None:
        return exact
    # Dynamic findings are assembled from stable fragments. Longest-first keeps
    # specific phrases from being consumed by short labels such as "Сейчас".
    result = text
    for source in sorted(RU_TO_EN, key=len, reverse=True):
        if source in result:
            result = result.replace(source, RU_TO_EN[source])
    return result
